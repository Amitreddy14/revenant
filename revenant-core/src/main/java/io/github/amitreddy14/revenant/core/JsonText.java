package io.github.amitreddy14.revenant.core;

/**
 * The one piece of JSON the engine has to write itself: failure messages. Everything else is
 * opaque JSON handed in by callers, so the core module needs no JSON library.
 */
final class JsonText {

    private JsonText() {}

    /** Returns {@code text} as a JSON string literal, including the surrounding quotes. */
    static String quote(String text) {
        StringBuilder out = new StringBuilder(text.length() + 2).append('"');
        for (int i = 0; i < text.length(); i++) {
            char c = text.charAt(i);
            switch (c) {
                case '"' -> out.append("\\\"");
                case '\\' -> out.append("\\\\");
                case '\n' -> out.append("\\n");
                case '\r' -> out.append("\\r");
                case '\t' -> out.append("\\t");
                case '\b' -> out.append("\\b");
                case '\f' -> out.append("\\f");
                default -> {
                    if (c < 0x20) {
                        out.append(String.format("\\u%04x", (int) c));
                    } else {
                        out.append(c);
                    }
                }
            }
        }
        return out.append('"').toString();
    }
}
